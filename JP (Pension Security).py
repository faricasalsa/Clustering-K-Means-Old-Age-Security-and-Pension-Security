outlier_indices_iqr = set()

for i, feature in enumerate(features):
    Q1 = df_jp[feature].quantile(0.25)
    Q3 = df_jp[feature].quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outliers = df_jp[(df_jp[feature] < lower_bound) | (df_jp[feature] > upper_bound)]

    print(f"\n{feature}:")
    print(f"  Q1: {Q1:.2f}, Q3: {Q3:.2f}, IQR: {IQR:.2f}")
    print(f"  Lower bound: {lower_bound:.2f}, Upper bound: {upper_bound:.2f}")
    print(f"  Outliers detected: {len(outliers)}")

    for idx, row in outliers.iterrows():
        outlier_indices_iqr.add(idx)
        print(f"    - {row['Bulan']} {row['Tahun']}: {row[feature]:.2f}")

print(f"\nTotal unique outliers detected dengan IQR: {len(outlier_indices_iqr)}")

# Metode 3: Mahalanobis Distance untuk multivariate outlier detection
print("\n=== DETEKSI OUTLIER MULTIVARIATE MENGGUNAKAN MAHALANOBIS DISTANCE ===")

