# Metode Elbow dengan Davies-Bouldin Index
def find_optimal_clusters_enhanced(data, max_clusters=6):
    wcss = []
    silhouette_scores = []
    db_scores = []

    for i in range(2, max_clusters+1):
        kmeans = KMeans(n_clusters=i, random_state=42, n_init=10)
        kmeans.fit(data)
        wcss.append(kmeans.inertia_)

        # Hitung silhouette score
        silhouette_avg = silhouette_score(data, kmeans.labels_)
        silhouette_scores.append(silhouette_avg)

        # Hitung Davies-Bouldin Index
        db_index = davies_bouldin_score(data, kmeans.labels_)
        db_scores.append(db_index)

    # Plot Elbow Method dan Davies-Bouldin Index
    plt.figure(figsize=(18, 5))

    plt.subplot(1, 3, 1)
    plt.plot(range(2, max_clusters+1), wcss, marker='o', linestyle='--', color='b', linewidth=2)
    plt.title('Elbow Method - Inertia vs Jumlah Cluster')
    plt.xlabel('Jumlah Cluster (K)')
    plt.ylabel('WCSS (Within-Cluster Sum of Squares)')
    plt.grid(True, alpha=0.3)

    # Tandai titik elbow
    elbow_point = 3  # Berdasarkan analisis sebelumnya
    plt.axvline(x=elbow_point, color='r', linestyle='--', alpha=0.7, label=f'Elbow point (K={elbow_point})')
    plt.legend()

    # Plot Silhouette Analysis
    plt.subplot(1, 3, 2)
    plt.plot(range(2, max_clusters+1), silhouette_scores, marker='s', linestyle='--', color='g', linewidth=2)
    plt.title('Silhouette Analysis - Rata-rata Silhouette Score vs Jumlah Cluster')
    plt.xlabel('Jumlah Cluster (K)')
    plt.ylabel('Rata-rata Silhouette Score')
    plt.grid(True, alpha=0.3)

    # Tandai silhouette score tertinggi
    best_k_silhouette = np.argmax(silhouette_scores) + 2
    best_score = silhouette_scores[best_k_silhouette-2]
    plt.axvline(x=best_k_silhouette, color='r', linestyle='--', alpha=0.7,
                label=f'Best K={best_k_silhouette} (score={best_score:.3f})')
    plt.legend()

    # Plot Davies-Bouldin Index
    plt.subplot(1, 3, 3)
    plt.plot(range(2, max_clusters+1), db_scores, marker='^', linestyle='--', color='purple', linewidth=2)
    plt.title('Davies-Bouldin Index vs Jumlah Cluster')
    plt.xlabel('Jumlah Cluster (K)')
    plt.ylabel('Davies-Bouldin Index')
    plt.grid(True, alpha=0.3)

    # Tandai Davies-Bouldin Index terendah (lebih baik)
    best_k_db = np.argmin(db_scores) + 2
    best_db_score = db_scores[best_k_db-2]
    plt.axvline(x=best_k_db, color='r', linestyle='--', alpha=0.7,
                label=f'Best K={best_k_db} (score={best_db_score:.3f})')
    plt.legend()

    plt.tight_layout()
    plt.show()

    # Tampilkan hasil numerik
    print("\nHASIL ANALISIS OPTIMAL CLUSTER:")
    print("K\tWCSS\t\tSilhouette Score\tDavies-Bouldin Index")
    print("-" * 60)
    for i, (w, s, db) in enumerate(zip(wcss, silhouette_scores, db_scores)):
        k = i + 2
        print(f"{k}\t{w:.2f}\t\t{s:.4f}\t\t\t{db:.4f}")

    return wcss, silhouette_scores, db_scores

